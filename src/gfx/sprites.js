// 校验：行等长、只用调色板字符或 '.'
export function validateSprite(rows, palette = PALETTE) {
  const errors = [];
  if (!Array.isArray(rows) || rows.length === 0) return { ok: false, w: 0, h: 0, errors: ['empty'] };
  const w = rows[0].length;
  rows.forEach((row, y) => {
    if (row.length !== w) errors.push(`row ${y} length ${row.length} != ${w}`);
    for (const ch of row) {
      if (ch !== '.' && !(ch in palette)) errors.push(`row ${y} bad char '${ch}'`);
    }
  });
  return { ok: errors.length === 0, w, h: rows.length, errors };
}
